%% ---------------------------------------------------------------- helpers

function li = link_index(parts, links)
    [~, li] = ismember(string({parts.link}), links);
end

function s = blank_if_zero(v)
    s = ''; if v > 0, s = sprintf('%.0f', v); end
end

function s = ok_over(ok)
    s = 'OVER'; if ok, s = 'OK'; end
end

function H = joint_tf(p, axis, deg)
    % translate by p (mm), then rotate by deg about axis: one joint of talos_arm.joint_transforms
    a = axis(:)/norm(axis); K = [0 -a(3) a(2); a(3) 0 -a(1); -a(2) a(1) 0];
    H = eye(4);
    H(1:3, 1:3) = eye(3) + sind(deg)*K + (1 - cosd(deg))*K^2;
    H(1:3, 4) = p(:);
end

function F = link_frames(g, q, L2)
    % World frame of each link (4x4xN); joint k's axis passes through frame k+1. Same as talos_arm.link_frames.
    J = {joint_tf([0 0 g.H_PAN], [0 0 1], q(1)), joint_tf([0 0 g.H_SH], [0 1 0], -90 + q(2)), ...
         joint_tf([g.L1 0 0], [0 1 0], q(3)), joint_tf([L2 0 0], [0 1 0], q(4)), ...
         joint_tf([g.X_ROLL 0 0], [1 0 0], q(5)), joint_tf([g.XJ 0 g.ZJ], [0 1 0], -q(6))};
    F = repmat(eye(4), 1, 1, 6);
    for k = 2:6, F(:, :, k) = F(:, :, k-1)*J{k-1}; end
end

function P = make_pose(parts, li, g, q, L2)
    % Every part's mass, world CoM (mm) and world inertia (kg*mm^2) for joint angles q (deg)
    P.F = link_frames(g, q, L2);
    P.li = li; P.m = [parts.m];
    n = numel(parts);
    P.r = zeros(3, n); P.Iw = zeros(3, 3, n);
    for k = 1:n
        Rk = P.F(1:3, 1:3, li(k));
        P.r(:, k) = Rk*parts(k).com + P.F(1:3, 4, li(k));
        P.Iw(:, :, k) = Rk*parts(k).I*Rk';
    end
end

function p = pose_point(P, link, local)
    p = P.F(1:3, 1:3, link)*local + P.F(1:3, 4, link);
end

function [a, o, idx] = joint_axis(P, joint)
    % axis direction, a point on it, and the index of the first link it moves
    switch joint
        case "pan",        idx = 2; k = 3;
        case "shoulder",   idx = 3; k = 2;
        case "elbow",      idx = 4; k = 2;
        case "wrist_flex", idx = 5; k = 2;
        case "wrist_roll", idx = 6; k = 1;
    end
    a = P.F(1:3, k, idx); o = P.F(1:3, 4, idx);
end

function tau = gravity_torque(P, joint, payload, at, G, payload_only)
    % Torque (N*m) the joint must hold against gravity. payload_only: just the payload's share.
    if nargin < 6, payload_only = false; end
    [a, o, idx] = joint_axis(P, joint);
    down = [0; 0; -G];
    tau = 0;
    if ~payload_only
        sel = P.li >= idx;
        tau = a' * sum(cross((P.r(:, sel) - o)/1000, down*P.m(sel)), 2);
    end
    if payload
        tau = tau + a' * cross((pose_point(P, 6, at) - o)/1000, payload*down);
    end
    tau = abs(tau);
end

function J = inertia(P, joint, payload, at)
    % Moment of inertia (kg*m^2) of everything the joint moves, about its axis
    [a, o, idx] = joint_axis(P, joint);
    J = 0;
    for k = find(P.li >= idx)
        d = P.r(:, k) - o;
        J = J + P.m(k)*(d'*d - (d'*a)^2) + a'*P.Iw(:, :, k)*a;
    end
    d = pose_point(P, 6, at) - o;
    J = (J + payload*(d'*d - (d'*a)^2))*1e-6;
end

function q = ik(r, z, tool_elev, g, D_TOOL)
    % Planar IK: payload centre at radius r, height z (mm), tool at tool_elev (deg). [] if out of reach.
    wx = r - D_TOOL*cosd(tool_elev);
    wz = z - D_TOOL*sind(tool_elev) - (g.H_PAN + g.H_SH);
    c3 = (wx^2 + wz^2 - g.L1^2 - g.L2^2)/(2*g.L1*g.L2);
    q = [];
    if abs(c3) > 1, return; end
    q3 = acos(c3);
    e2 = atan2(wz, wx) + atan2(g.L2*sin(q3), g.L1 + g.L2*cos(q3));
    e3 = e2 - q3;
    q = [0, 90 - rad2deg(e2), rad2deg(q3), rad2deg(e3) - tool_elev, 0, 0];
end

function ok = within(q, R)
    ok = R.shoulder(1) <= q(2) && q(2) <= R.shoulder(2) && R.elbow(1) <= q(3) && q(3) <= R.elbow(2) ...
        && R.wrist_flex(1) <= q(4) && q(4) <= R.wrist_flex(2);
end

function b = beam_check(P, s, idx, payload, grip, tip_pt, G, E, gripper)
    % Bending moment, stress and tip-deflection share along one arm link, from its CAD sections
    Rl = P.F(1:3, 1:3, idx); o = P.F(1:3, 4, idx);
    tip = pose_point(P, gripper, tip_pt);
    px = pose_point(P, gripper, grip);
    n = numel(s.x);
    b.x = s.x; b.I_eff = s.I_eff; b.M = zeros(n, 1); b.sigma = zeros(n, 1); arm = zeros(n, 1);
    for k = 1:n
        st = Rl*[s.x(k); 0; 0] + o;
        % everything beyond the link, and this link's parts whose CoM is past the station
        sel = P.li > idx | (P.li == idx & P.r(1, :) > st(1));
        M = sum(P.m(sel).*G.*(P.r(1, sel) - st(1)))/1000 + payload*G*(px(1) - st(1))/1000;
        b.M(k) = M;
        b.sigma(k) = M*1000*s.c(k)/s.I_eff(k);
        arm(k) = tip(1) - st(1);
    end
    curv = b.M*1000./(E*b.I_eff);   % curvature integrated times the lever arm to the tip
    b.defl = sum(0.5*(curv(1:end-1) + curv(2:end)) .* 0.5.*(arm(1:end-1) + arm(2:end)) .* diff(b.x));
end

