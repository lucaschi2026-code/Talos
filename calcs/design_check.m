%% Talos design check: the CAD against the servo and the plastic
% Reads the CAD's masses, centres of mass, beam sections and joint ranges from cad_inputs.json
% (exported from cad/talos_arm.py by export_cad_inputs.py on the cad branch), runs every check,
% and writes design_check_results.md, shoulder_torque_cad.png and payload_envelope.png.
% Open it in MATLAB and press F5. It takes a few seconds.

clear; clc;
here = fileparts(mfilename('fullpath'));
if isempty(here), here = pwd; end
in = jsondecode(fileread(fullfile(here, 'cad_inputs.json')));
g = in.geometry;

%% Inputs (the same as design_check.py)
G = 9.81;
TAU_STALL = 2.94;          % N*m, STS3215 12 V (30 kg*cm)
LIMIT = TAU_STALL / 3;     % continuous-load limit, as in torque_check.m
COUNTS = 4096;             % encoder counts per revolution

% The mass model (PLA density, walls, infill, servo mass) is applied when the CAD is exported, so it
% comes in with the masses and beam sections. Change it in design_check.py and export again.
mm = in.mass_model;

E_PLA = 2.3e3;             % N/mm^2, printed PLA, conservative
SIGMA_ALLOW = 10.0;        % N/mm^2, sustained bending in printed PLA (creep-limited)
BEARING_ALLOW = 20.0;      % N/mm^2, screw bearing on a printed hole
HORN_SCREW_R = 7.0;        % mm, horn screw circle radius (14 mm circle)
HORN_SCREW_D = 3.0;        % mm, M3
MU_GRIP = 0.3;             % friction, PLA jaw on a typical object

PAYLOAD = 0.200;           % kg
GRIP_POINT = [88; 0; 0];   % payload centre in the gripper frame (mid-jaw), mm
TIP_POINT = [106; 0; 0];   % jaw tip in the gripper frame, mm
D_TOOL = g.X_ROLL + GRIP_POINT(1);   % wrist-flex axis -> payload centre, mm
HORIZONTAL = [0 90 0 0 0 0];         % arm straight out: worst case for gravity

links = string(in.links);
parts = in.parts;
gripper = 6;   % index of gripper_link
out = strings(0);

%% Mass budget
out(end+1) = sprintf('# Talos design check results\n');
out(end+1) = sprintf('Generated by `design_check.m` from `cad_inputs.json`, exported from the CAD in `cad/talos_arm.py` (cad branch, %s).\n', in.source.commit);
out(end+1) = sprintf('## Mass budget\n');
out(end+1) = sprintf('Printed parts: PLA %.2f g/cm3, %g mm perimeters/skins, %.0f%% infill. Servos: %.0f g + %.0f g screws and cable. The bus servo board is %.0f g, in the base.\n', ...
    mm.RHO_PLA*1e3, mm.T_SHELL, 100*mm.INFILL, mm.M_SERVO, mm.M_HARDWARE, mm.M_BOARD);
out(end+1) = '| Link | Printed (g) | Servo (g) | Board (g) | Total (g) |';
out(end+1) = '| --- | --- | --- | --- | --- |';
li = link_index(parts, links);
names = string({parts.name});
m = [parts.m];
is_servo = startsWith(names, 'servo');
is_board = names == "bus_servo_board";
for k = 1:numel(links)
    pr = sum(m(li == k & ~is_servo & ~is_board));
    sv = sum(m(li == k & is_servo));
    bd = sum(m(li == k & is_board));
    label = links(k); if k == 1, label = "base (fixed)"; end
    out(end+1) = sprintf('| %s | %.0f | %.0f | %s | %.0f |', label, pr*1000, sv*1000, ...
        blank_if_zero(bd*1000), (pr + sv + bd)*1000); %#ok<*SAGROW>
end
total = sum(m);
moving = sum(m(li >= 2));
out(end+1) = sprintf('| **total** | | | | **%.0f** |\n', total*1000);
out(end+1) = sprintf('Moving mass above the base: %.0f g.\n', moving*1000);
R = in.joint_ranges;

%% 1. Static holding torque
hz = make_pose(parts, li, g, HORIZONTAL, g.L2);
out(end+1) = sprintf('## 1. Static holding torque, arm straight out (worst case)\n');
out(end+1) = sprintf('Limit: %.2f N*m continuous (1/3 of %g N*m stall). Payload %.0f g at mid-jaw (%.0f mm past the wrist-flex axis).\n', ...
    LIMIT, TAU_STALL, PAYLOAD*1000, D_TOOL);
out(end+1) = '| Joint | No payload (N*m) | With payload (N*m) | % stall | vs limit |';
out(end+1) = '| --- | --- | --- | --- | --- |';
pitch = ["shoulder", "elbow", "wrist_flex"];
static = struct();
for j = pitch
    t0 = gravity_torque(hz, j, 0, GRIP_POINT, G);
    t1 = gravity_torque(hz, j, PAYLOAD, GRIP_POINT, G);
    static.(j) = [t0 t1];
    out(end+1) = sprintf('| %s | %.2f | %.2f | %.0f %% | %s (%.2fx) |', j, t0, t1, 100*t1/TAU_STALL, ...
        ok_over(t1 <= LIMIT), t1/LIMIT);
end
roll = 0;
for a = 0:15:345
    roll = max(roll, gravity_torque(make_pose(parts, li, g, [0 90 0 0 a 0], g.L2), "wrist_roll", PAYLOAD, GRIP_POINT, G));
end
out(end+1) = sprintf('| wrist_roll (worst roll angle) | | %.3f | %.1f %% | OK |', roll, 100*roll/TAU_STALL);
tip_sh = gravity_torque(hz, "shoulder", PAYLOAD, TIP_POINT, G);
out(end+1) = sprintf('\nPayload held at the very tip instead: shoulder %.2f N*m.\n', tip_sh);
share = PAYLOAD * gravity_torque(hz, "shoulder", 1, GRIP_POINT, G, true);
out(end+1) = sprintf('The payload is %.2f N*m of the shoulder load (%.0f %%).\n', share, 100*share/static.shoulder(2));

out(end+1) = sprintf('### Against the earlier `torque_check.m` model\n');
out(end+1) = '| | torque_check.m (SO-101 values) | This CAD |';
out(end+1) = '| --- | --- | --- |';
out(end+1) = sprintf('| Upper arm L1 | 120 mm | %.0f mm |', g.L1);
out(end+1) = sprintf('| Forearm L2 | 120 mm | %.0f mm |', g.L2);
out(end+1) = sprintf('| Wrist flex -> tip | 160 mm | %.0f mm |', g.X_ROLL + TIP_POINT(1));
out(end+1) = sprintf('| Moving links (4) | 385 g | %.0f g |', sum(m(li >= 3))*1000);
out(end+1) = sprintf('| Shoulder, 200 g payload | 1.62 N*m | %.2f N*m |', static.shoulder(2));
out(end+1) = sprintf('| Elbow, 200 g payload | 0.96 N*m | %.2f N*m |\n', static.elbow(2));

out(end+1) = sprintf('Lumped inputs for `torque_check.m` and `pan_base_check.m` (per-link mass incl. servo, CoM distance from the link''s own joint, arm straight):\n');
out(end+1) = '```';
lumps = {3, 'upper arm + elbow servo', "shoulder"; 4, 'forearm + wrist-flex servo', "elbow"; ...
         5, 'wrist + wrist-roll servo', "wrist_flex"; 6, 'gripper + jaw servo', "wrist_flex"};
for k = 1:size(lumps, 1)
    sel = li == lumps{k, 1};
    ml = sum(hz.m(sel));
    cx = sum(hz.m(sel) .* hz.r(1, sel)) / ml;
    [~, o] = joint_axis(hz, lumps{k, 3});
    out(end+1) = sprintf('%-28s m = %.3f kg, CoM %6.1f mm from %s axis', lumps{k, 2}, ml, cx - o(1), lumps{k, 3});
end
out(end+1) = sprintf('```\n');

% shoulder torque vs elevation
elev = -90:5:90;
fig = figure('Visible', 'off', 'Units', 'inches', 'Position', [1 1 7 4.2]);
hold on; styles = ["-", "--", ":"];
for k = 1:3
    q3 = 45*(k - 1);
    tau = arrayfun(@(e) gravity_torque(make_pose(parts, li, g, [0 90-e q3 0 0 0], g.L2), "shoulder", PAYLOAD, GRIP_POINT, G), elev);
    plot(elev, tau, styles(k), 'LineWidth', 1.8, 'DisplayName', sprintf('elbow bent %d deg', q3));
end
yline(LIMIT, '--', 'Color', [0.84 0.15 0.16], 'DisplayName', '1/3 stall');
yline(TAU_STALL, '-k', 'DisplayName', 'stall');
xregion(-90, 90 - R.shoulder(2), 'FaceColor', [0.85 0.85 0.85], 'DisplayName', 'beyond shoulder stop');
xlim([-90 90]); grid on; legend('FontSize', 8, 'Location', 'best');
xlabel('Upper-arm elevation from horizontal (deg)'); ylabel('Shoulder torque (N*m)');
title(sprintf('Shoulder torque with %.0f g payload (CAD masses)', PAYLOAD*1000));
save_plot(fig, fullfile(here, 'shoulder_torque_cad.png'));
out(end+1) = sprintf('![Shoulder torque vs elevation](shoulder_torque_cad.png)\n');

%% 2. Joint ranges
out(end+1) = sprintf('## 2. Joint ranges from CAD collision sweep\n');
out(end+1) = sprintf('Swept in 5 deg steps until any solid overlaps by more than 1 mm3. Angles in the model convention (shoulder 0 = upper arm vertical, + = forward/down).\n');
out(end+1) = '| Joint | Min (deg) | Max (deg) | Span (deg) |';
out(end+1) = '| --- | --- | --- | --- |';
for f = string(fieldnames(R))'
    out(end+1) = sprintf('| %s | %d | %d | %d |', f, R.(f)(1), R.(f)(2), R.(f)(2) - R.(f)(1));
end
out(end+1) = sprintf('| pan, wrist_roll | no mechanical stop | | servo 0-360 deg, cable-limited |\n');
out(end+1) = sprintf('What stops each pitch joint one step (5 deg) past its limit, from `cad/joint_sweep.py` (cad branch):\n');
out(end+1) = '- shoulder ±105: the upper arm meets the shoulder (about 175 mm3), and its idler plate touches the shoulder servo''s plugs (1.4 mm3).';
out(end+1) = '- elbow ±105: the forearm''s idler plate touches the elbow servo''s plugs (1.4 mm3).';
out(end+1) = '- wrist flex -105: the wrist touches the wrist flex servo''s plugs (1.4 mm3).';
out(end+1) = sprintf('- wrist flex +100: the wrist meets the forearm (149 mm3).\n');
out(end+1) = sprintf('The plug touches are small: the plug model is a padded box. ±100 is kept on purpose, since SO-101''s elbow is ±97. Set the software limits inside these ranges.\n');

%% 3. Payload envelope
out(end+1) = sprintf('## 3. Payload envelope\n');
out(end+1) = sprintf('Largest payload that keeps shoulder, elbow and wrist under the continuous limit, from IK over the reachable workspace.\n');
tasks = {'top-down pick, object centre 25 mm above table', 25, -90; ...
         'side grasp, object centre 45 mm above table', 45, 0; ...
         'horizontal reach at shoulder height', g.H_PAN + g.H_SH, 0};
fig = figure('Visible', 'off', 'Units', 'inches', 'Position', [1 1 7 4.2]);
hold on; env = {};
for k = 1:size(tasks, 1)
    rs = []; ms = [];
    for r = 60:5:455
        q = ik(r, tasks{k, 2}, tasks{k, 3}, g, D_TOOL);
        if isempty(q) || ~within(q, R), continue; end
        pz = make_pose(parts, li, g, q, g.L2);
        cap = inf;
        for j = pitch
            u = gravity_torque(pz, j, 1, GRIP_POINT, G, true);
            if u > 1e-9, c = (LIMIT - gravity_torque(pz, j, 0, GRIP_POINT, G)) / u; else, c = 9.9; end
            cap = min(cap, c);
        end
        rs(end+1) = r; ms(end+1) = max(cap, 0) * 1000;
    end
    plot(rs, min(ms, 1500), 'LineWidth', 1.8, 'DisplayName', tasks{k, 1});
    if ~isempty(rs), env(end+1, :) = {tasks{k, 1}, min(rs), max(rs), max(rs(ms >= PAYLOAD*1000))}; end
end
yline(PAYLOAD*1000, '--', 'Color', [0.84 0.15 0.16], 'DisplayName', sprintf('%.0f g target', PAYLOAD*1000));
xlabel('Payload radius from base axis (mm)'); ylabel('Max continuous payload (g)');
ylim([0 1500]); grid on; legend('FontSize', 8, 'Location', 'best');
title('Payload envelope (1/3-stall limit on every pitch joint)');
save_plot(fig, fullfile(here, 'payload_envelope.png'));
out(end+1) = '| Task | Reachable radius (mm) | 200 g OK out to (mm) |';
out(end+1) = '| --- | --- | --- |';
for k = 1:size(env, 1)
    r200 = 'never'; if ~isempty(env{k, 4}), r200 = sprintf('%d', env{k, 4}); end
    out(end+1) = sprintf('| %s | %.0f - %.0f | %s |', env{k, 1}, env{k, 2}, env{k, 3}, r200);
end
out(end+1) = sprintf('\n![Payload envelope](payload_envelope.png)\n');

%% 4. Dynamic torque
out(end+1) = sprintf('## 4. Dynamic torque\n');
out(end+1) = sprintf('Triangular velocity profile (accelerate half way, decelerate half way): alpha = 4*theta/t^2, omega_peak = 2*theta/t.\n');
out(end+1) = '| Joint | Move | Inertia (kg*m^2) | alpha (rad/s^2) | omega peak (rpm) | Accel torque (N*m) | Static + accel (N*m) | % stall |';
out(end+1) = '| --- | --- | --- | --- | --- | --- | --- | --- |';
for row = {"pan", 180, 1.5; "shoulder", 90, 1.0; "elbow", 90, 0.8}'
    [j, deg, t] = row{:};
    J = inertia(hz, j, PAYLOAD, GRIP_POINT);
    th = deg2rad(deg);
    alpha = 4*th/t^2; om = 2*th/t;
    acc = J*alpha;
    st = 0; if j ~= "pan", st = gravity_torque(hz, j, PAYLOAD, GRIP_POINT, G); end
    out(end+1) = sprintf('| %s | %d deg in %.1f s | %.4f | %.1f | %.0f | %.3f | %.2f | %.0f %% |', ...
        j, deg, t, J, alpha, om*60/(2*pi), acc, st + acc, 100*(st + acc)/TAU_STALL);
end
out(end+1) = sprintf('\nPeak speeds are well under the servo''s no-load speed (about 0.22 s/60 deg, 45 rpm at 12 V; check the datasheet for your variant). Short peaks above the 1/3 line are fine; the limit is for sustained holding.\n');

%% 5. Pan servo overturning moment and tipping
out(end+1) = sprintf('## 5. Base: pan servo overturning moment and tipping\n');
[~, o, idx] = joint_axis(hz, "pan");
down = [0; 0; -G];
sel = hz.li >= idx;
Mot = sum(cross((hz.r(:, sel) - o)/1000, down*hz.m(sel)), 2);
pr = pose_point(hz, gripper, GRIP_POINT);
Mot = Mot + cross((pr - o)/1000, PAYLOAD*down);
Mot_h = hypot(Mot(1), Mot(2));
out(end+1) = sprintf('With the arm straight out, the pan servo''s output shaft carries an overturning moment of **%.2f N*m** plus %.1f N of axial load. On the SO-101 layout this goes through the servo''s own output bearing, and the turntable rides 2.8 mm clear of the column.\n', ...
    Mot_h, (moving + PAYLOAD)*G);
apothem = 66*cosd(15)/1000;
m_all = total + PAYLOAD;
xg = (sum(hz.m .* hz.r(1, :)) + PAYLOAD*pr(1)) / m_all / 1000;
M_tip = m_all*G*(xg - apothem);
tipping = sprintf('Whole-arm centre of mass is %.0f mm from the base axis; the base edge is %.0f mm out. ', xg*1000, apothem*1000);
if M_tip > 0
    bolt_x = 54*cosd(45)/1000;
    out(end+1) = tipping;
    out(end+1) = sprintf('**The arm tips over unless the base is fixed down** (net overturning %.2f N*m). Clamping through the two rear M4 holes needs %.1f N per bolt before dynamic loads; an M4 bolt in a printed counterbore is good for well over 100 N.\n', ...
        M_tip, M_tip/(apothem + bolt_x)/2);
else
    out(end+1) = tipping;
    out(end+1) = sprintf('The arm is stable on its own (margin %.2f N*m).\n', -M_tip);
end

%% 6. Link bending stress and deflection
out(end+1) = sprintf('## 6. Link bending stress and deflection\n');
out(end+1) = sprintf('Arm straight out with %.0f g. Sections are cut from the CAD every 2 mm; the core inside the %g mm perimeters is counted at %.0f%% stiffness. E = %.1f GPa, allowable %.0f MPa sustained.\n', ...
    PAYLOAD*1000, mm.T_SHELL, 100*mm.INFILL, E_PLA/1000, SIGMA_ALLOW);
out(end+1) = '| Link | Worst station (mm from joint) | Moment (N*m) | I_eff (mm^4) | Stress (MPa) | Safety factor | Tip deflection (mm) |';
out(end+1) = '| --- | --- | --- | --- | --- | --- | --- |';
total_defl = 0;
for link = ["upper_arm_link", "forearm_link"]
    b = beam_check(hz, in.beams.(link), find(links == link), PAYLOAD, GRIP_POINT, TIP_POINT, G, E_PLA, gripper);
    total_defl = total_defl + b.defl;
    [~, w] = max(b.sigma);
    out(end+1) = sprintf('| %s | %.0f | %.2f | %.0f | %.1f | %.1f | %.2f |', link, b.x(w), b.M(w), b.I_eff(w), ...
        b.sigma(w), SIGMA_ALLOW/b.sigma(w), b.defl);
end
out(end+1) = sprintf('\nTip sag from bending of the two printed links: about %.1f mm.\n', total_defl);

%% 7. Horn screws and clevis plates
out(end+1) = sprintf('## 7. Horn screw bearing\n');
out(end+1) = sprintf('All joint torque goes through the output horn''s 4 screws (the idler side only supports). Bearing stress on the printed clevis plate:\n');
t_plate = g.CLV_OUT - g.HORN_FACE;   % the screws bear on the plate and the pad round them
out(end+1) = '| Joint | Peak torque (N*m) | Force per screw (N) | Bearing stress (MPa) | Safety factor |';
out(end+1) = '| --- | --- | --- | --- | --- |';
for row = {'shoulder (servo stall)', TAU_STALL; 'shoulder (holding, 200 g)', static.shoulder(2)}'
    F = row{2} / (4*HORN_SCREW_R/1000);
    sb = F / (HORN_SCREW_D*t_plate);
    out(end+1) = sprintf('| %s | %.2f | %.0f | %.1f | %.1f |', row{1}, row{2}, F, sb, BEARING_ALLOW/sb);
end
out(end+1) = sprintf('\nPlate and pad %.1f mm thick at the screws, M%.0f screws on a %.0f mm circle, allowable %.0f MPa.\n', ...
    t_plate, HORN_SCREW_D, 2*HORN_SCREW_R, BEARING_ALLOW);
n_tab = g.n_idler_tab_screws;
out(end+1) = sprintf('The idler plates on the upper arm and forearm are a separate part (TAL-110), held by %d M3 screws into the beam. They only support the passive horn, so worst case they carry the whole joint reaction (everything beyond the joint plus the payload), doubled for dynamics:\n', n_tab);
out(end+1) = '| Idler plate | Joint reaction x2 (N) | Force per screw (N) | Bearing stress (MPa) | Safety factor |';
out(end+1) = '| --- | --- | --- | --- | --- |';
for row = {"upper_arm_link", "shoulder"; "forearm_link", "elbow"}'
    F = 2*(sum(m(li >= find(links == row{1}))) + PAYLOAD)*G;
    sb = F/n_tab / (HORN_SCREW_D*t_plate);
    out(end+1) = sprintf('| %s (%s) | %.1f | %.1f | %.2f | %.0f |', row{1}, row{2}, F, F/n_tab, sb, BEARING_ALLOW/sb);
end
out(end+1) = '';
t_clv = g.CLV_OUT - g.CLV_IN;
out(end+1) = sprintf('### Output clevis plates\n');
out(end+1) = sprintf('The output horn''s torque reaches the link through the output clevis plate, bending it in its own plane about the joint axis. At the plate''s root, where it joins the link, it is a %.1f mm by h rectangle: stress 6 T / (t h²). The plates stand vertical in every print, so that stress runs along the layers.\n', t_clv);
out(end+1) = '| Joint (plate) | Root height h (mm) | Holding, 200 g (N*m) | Stress (MPa) | SF | Stall (N*m) | Stress (MPa) | SF |';
out(end+1) = '| --- | --- | --- | --- | --- | --- | --- | --- |';
for row = {"shoulder", 'upper arm', 30; "elbow", 'forearm', 30; "wrist_flex", 'wrist', 24}'
    [j, plate, h] = row{:};
    hold_t = static.(j)(2);
    s_hold = 6*hold_t*1000/(t_clv*h^2); s_stall = 6*TAU_STALL*1000/(t_clv*h^2);
    out(end+1) = sprintf('| %s (%s) | %.0f | %.2f | %.1f | %.1f | %.2f | %.1f | %.1f |', j, plate, h, hold_t, s_hold, ...
        SIGMA_ALLOW/s_hold, TAU_STALL, s_stall, SIGMA_ALLOW/s_stall);
end
out(end+1) = sprintf('\nThe wrist''s root height is its clevis, 2 × 12, without the flat-top extension that makes it taller (so it errs safe). The plates are %.1f mm thick since they moved out to %g mm, 1 mm clear of the shell. In-plane bending scales with the thickness, not its square, so the 4.0 mm plates had %.3f of these stresses. Stall is checked against the sustained (creep) limit too, so an SF a little over 1 there still leaves the short-term strength of PLA, several times higher, in hand.\n', ...
    t_clv, g.CLV_IN, t_clv/4.0);

%% 8. Gripper
out(end+1) = sprintf('## 8. Gripper\n');
r_mid = 43.0; r_tip = 64.0;
for row = {'continuous (1/3 stall)', LIMIT; 'stall', TAU_STALL}'
    out(end+1) = sprintf('- Grip force, %s: %.0f N at mid-jaw, %.0f N at the tip.', row{1}, row{2}/(r_mid/1000), row{2}/(r_tip/1000));
end
F = LIMIT/(r_mid/1000);
out(end+1) = sprintf('- With friction %g on both jaws, the continuous grip holds %.1f kg; the 200 g target needs only %.1f N of squeeze, so run the jaw servo at a low torque limit to avoid crushing parts.', ...
    MU_GRIP, 2*MU_GRIP*F/G, PAYLOAD*G/(2*MU_GRIP));
fr = in.finger_root;
x_contact = g.XJ + r_mid;
for row = {'continuous', LIMIT; 'stall', TAU_STALL}'
    M = row{2}/(r_mid/1000) * (x_contact - fr.x)/1000;
    sig = M*1000*fr.c/fr.I_eff;
    out(end+1) = sprintf('- Fixed finger root (%.0f mm wide, %.0f mm out), %s grip: %.2f N*m, %.1f MPa, safety factor %.1f.', ...
        2*g.FINGER_HW, fr.x, row{1}, M, sig, SIGMA_ALLOW/sig);
end
o_max = R.gripper(2);
th = deg2rad(o_max);
jaw_tip = [64*cos(th) + 5.5*sin(th), 64*sin(th) - 5.5*cos(th)];
out(end+1) = sprintf('- Jaw opens %d deg before hitting the housing: about %.0f mm between the jaw tips.', o_max, jaw_tip(2) + g.ZJ + 0.5);
out(end+1) = '';

%% 9. Resolution
out(end+1) = sprintf('## 9. Resolution and stiffness at the tip\n');
step = 2*pi/COUNTS;
out(end+1) = '| Joint | Lever arm to tip (mm) | Tip motion per encoder count (mm) | per 0.5 deg backlash (mm) |';
out(end+1) = '| --- | --- | --- | --- |';
tip = pose_point(hz, gripper, TIP_POINT);
arms = 0;
for j = pitch
    [~, o] = joint_axis(hz, j);
    r = norm(tip([1 3]) - o([1 3]))/1000;
    arms = arms + r;
    out(end+1) = sprintf('| %s | %.0f | %.2f | %.1f |', j, r*1000, r*step*1000, r*deg2rad(0.5)*1000);
end
out(end+1) = sprintf('\nOne count on every pitch joint moves the tip up to %.1f mm. Repeatability will be set by gear backlash and the %.1f mm link sag, not by encoder resolution.\n', ...
    arms*step*1000, total_defl);

%% 10. Forearm length sensitivity
out(end+1) = sprintf('## 10. Forearm length sensitivity\n');
out(end+1) = sprintf('CAD rebuilt with a different elbow-to-wrist length; everything else unchanged. Arm straight out, 200 g payload.\n');
out(end+1) = '| Forearm L2 (mm) | Reach, shoulder to tip (mm) | Shoulder (N*m) | Elbow (N*m) | Elbow vs limit |';
out(end+1) = '| --- | --- | --- | --- | --- |';
variants = [num2cell(in.forearm_variants(:)); {struct('L2', g.L2, 'parts', parts)}];
for k = 1:numel(variants)
    v = variants{k};
    pz = make_pose(v.parts, link_index(v.parts, links), g, HORIZONTAL, v.L2);
    sh = gravity_torque(pz, "shoulder", PAYLOAD, GRIP_POINT, G);
    el = gravity_torque(pz, "elbow", PAYLOAD, GRIP_POINT, G);
    mark = ''; if v.L2 == g.L2, mark = ' (design)'; end
    out(end+1) = sprintf('| %.0f%s | %.0f | %.2f | %.2f | %.2fx |', v.L2, mark, g.L1 + v.L2 + g.X_ROLL + TIP_POINT(1), sh, el, el/LIMIT);
end
out(end+1) = '';

%% 11. Servo mounts
out(end+1) = sprintf('## 11. Servo mounts\n');
out(end+1) = sprintf('### Shoulder cradle\n');
z_screws = g.H_SH + (g.CASE_FRONT_X + g.CASE_BACK_X)/2;
z_root = 6.0;   % turntable top
% turning about its case screws, the case meets whatever is closest in angle: the cradle walls' top
% edge (FIT_C off) or the posts beside the shaft (POST_IN - CASE_HW off)
tilt_cradle = g.FIT_C/(g.CRADLE_TOP - z_screws);
tilt_post = (g.POST_IN - g.CASE_HW)/(g.shoulder_top_z - z_screws);
first = ''; if tilt_cradle >= tilt_post, first = ' (NO: the posts are reached first)'; end
out(end+1) = sprintf('The shoulder servo''s reaction torque is a couple between its case screws, low in the cradle, and whatever its case bears on higher up. Turning about the screws, it reaches the top of the cradle''s side walls after %.1f mrad and the posts beside the shaft after %.1f mrad, so the cradle carries it%s. The cradle''s two long walls (±Y) take that force in their own plane, as cantilevers from the turntable. Their bending stress runs across the layer lines (the shoulder prints turntable down), so it is checked against the same allowable as the links. The -Y wall''s doubler is left out.\n', ...
    1000*tilt_cradle, 1000*tilt_post, first);
out(end+1) = '| Load | Torque (N*m) | Force at the cradle top (N) | Root moment (N*m) | Stress (MPa) | Safety factor |';
out(end+1) = '| --- | --- | --- | --- | --- | --- |';
walls_t = (g.SHELL_OUT - g.TOP_FACE - g.FIT_C) + (g.SHELL_OUT - g.SHELL_IN);
depth = 34.0;   % cradle length along X
I_walls = walls_t*depth^3/12; c_walls = depth/2;
for row = {'holding, no payload', static.shoulder(1); 'holding, 200 g', static.shoulder(2); 'servo stall', TAU_STALL}'
    F = row{2}/((g.CRADLE_TOP - z_screws)/1000);
    M = F*(g.CRADLE_TOP - z_root)/1000;
    sig = M*1000*c_walls/I_walls;
    out(end+1) = sprintf('| %s | %.2f | %.0f | %.2f | %.1f | %.1f |', row{1}, row{2}, F, M, sig, SIGMA_ALLOW/sig);
end
out(end+1) = sprintf('\nCase screws at z %.1f, cradle top at %g, root at %g; the ±Y walls are %.1f mm thick together and %g mm long. Allowable %.0f MPa sustained. The posts stand %g mm off the case (the first design had 0.5 mm, so the posts took the torque and reached 14 MPa at stall).\n', ...
    z_screws, g.CRADLE_TOP, z_root, walls_t, depth, SIGMA_ALLOW, g.POST_IN - g.CASE_HW);
out(end+1) = sprintf('### Pan servo case screws\n');
out(end+1) = sprintf('The pan servo carries the %.2f N*m overturning moment into the base through its bottom face and its case screws. The servo tips about an edge of its bottom face; the screws on the far side hold it down. The arm pans, so the moment can point any way.\n', Mot_h);
out(end+1) = '| Tipping about | Far pair only, per screw (N) | Both pairs, per screw (N) |';
out(end+1) = '| --- | --- | --- |';
far = g.CASE_BACK_X; near = g.CASE_BACK_SHAFT_X; hy = g.CASE_BACK_Y; M = Mot_h*1000;
edges = {'the shaft-side edge of the bottom face', [1 1]*(g.FACE_X - far), [[1 1]*(g.FACE_X - far), [1 1]*(g.FACE_X - near)]; ...
         'the far end', [1 1]*(far - g.CASE_X0), [[1 1]*(far - g.CASE_X0), [1 1]*(near - g.CASE_X0)]; ...
         'a long side', [g.CASE_HW - hy, g.CASE_HW + hy], [g.CASE_HW - hy, g.CASE_HW + hy, g.CASE_HW - hy, g.CASE_HW + hy]};
worst4 = 0;
for k = 1:size(edges, 1)
    f2 = M*max(edges{k, 2})/sum(edges{k, 2}.^2);
    f4 = M*max(edges{k, 3})/sum(edges{k, 3}.^2);
    worst4 = max(worst4, f4);
    out(end+1) = sprintf('| %s | %.0f | %.0f |', edges{k, 1}, f2, f4);
